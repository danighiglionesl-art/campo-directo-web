interface QrCodeSvgProps {
  className?: string;
  size?: number;
}

export const QrCodeSvg: React.FC<QrCodeSvgProps> = ({
  className = "w-48 h-48",
  size = 200,
}) => {
  const margin = 2; // Margen de seguridad (quiet zone)
  const matrixSize = QR_MATRIX_INSTALAR.length;
  const viewBoxSize = matrixSize + margin * 2;

  // Generamos un solo path para un renderizado ultra eficiente
  let pathData = "";
  for (let r = 0; r < matrixSize; r++) {
    for (let c = 0; c < matrixSize; c++) {
      if (QR_MATRIX_INSTALAR[r][c] === 1) {
        const x = c + margin;
        const y = r + margin;
        pathData += `M${x},${y}h1v1h-1z `;
      }
    }
  }

  return (
    <div className={`relative inline-block bg-white p-3 rounded-2xl shadow-sm border border-slate-200/80 ${className}`}>
      <svg
        viewBox={`0 0 ${viewBoxSize} ${viewBoxSize}`}
        width={size}
        height={size}
        className="w-full h-full"
        fill="currentColor"
        aria-label="Código QR para instalar Campo Directo"
      >
        <rect
          x="0"
          y="0"
          width={viewBoxSize}
          height={viewBoxSize}
          fill="#ffffff"
          rx="1"
        />
        <path d={pathData} fill="#1e293b" />
      </svg>
    </div>
  );
};
