// Asignación de imagen agrícola de calidad según categoría técnica
export function getProductImage(category: string, rubro: "Insumos" | "Semillas"): string {
  const cat = (category || "").toUpperCase();
  if (rubro === "Semillas") {
    if (cat.includes("SOJA")) return "https://images.unsplash.com/photo-1592982537447-7440770cbfc9?auto=format&fit=crop&w=600&q=80";
    if (cat.includes("MAÍZ") || cat.includes("MAIZ")) return "https://images.unsplash.com/photo-1551754655-cd27e38d2076?auto=format&fit=crop&w=600&q=80";
    if (cat.includes("TRIGO")) return "https://images.unsplash.com/photo-1500382017468-9049fed747ef?auto=format&fit=crop&w=600&q=80";
    if (cat.includes("GIRASOL")) return "https://images.unsplash.com/photo-1597848212624-a19eb35e2651?auto=format&fit=crop&w=600&q=80";
    return "https://images.unsplash.com/photo-1574943320219-553eb213f72d?auto=format&fit=crop&w=600&q=80";
  }
  if (cat.includes("HERBICIDA")) return "https://images.unsplash.com/photo-1595974482597-4b8da8879bc5?auto=format&fit=crop&w=600&q=80";
  if (cat.includes("FUNGICIDA")) return "https://images.unsplash.com/photo-1585314062340-f1a5a7c9328d?auto=format&fit=crop&w=600&q=80";
  if (cat.includes("INSECTICIDA")) return "https://images.unsplash.com/photo-1530595467537-0b5996c41f2d?auto=format&fit=crop&w=600&q=80";
  if (cat.includes("FERTILIZANTE") || cat.includes("NUTRICI")) return "https://images.unsplash.com/photo-1628352081506-83c43123ed6d?auto=format&fit=crop&w=600&q=80";
  if (cat.includes("COADYUVANTE") || cat.includes("ACEITE")) return "https://images.unsplash.com/photo-1574943320219-553eb213f72d?auto=format&fit=crop&w=600&q=80";
  if (cat.includes("INOCULANTE") || cat.includes("CURASEMILLAS")) return "https://images.unsplash.com/photo-1589923188900-85dae523342b?auto=format&fit=crop&w=600&q=80";
  return "https://images.unsplash.com/photo-1585314062340-f1a5a7c9328d?auto=format&fit=crop&w=600&q=80";
}

